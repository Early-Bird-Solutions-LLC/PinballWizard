// Mermaid diagram validator for the documentation surface.
//
// Every ```mermaid block in README.md + docs/** (excluding docs/superpowers)
// is extracted and rendered by mermaid-cli (mmdc); any parse/render error
// fails the build. This is the productionized form of the headless-browser
// parse check used while authoring the diagrams — it keeps a broken diagram
// from shipping green.
//
// Requires @mermaid-js/mermaid-cli (mmdc) on PATH (the workflow installs it)
// and a puppeteer config enabling --no-sandbox on CI runners.
//
// Usage: node tools/docs/validate-mermaid.mjs   (run from repo root)

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execSync } from 'node:child_process';

const ROOT = process.cwd();

function walk(dir, acc) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'superpowers') continue;
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, acc);
    else if (entry.name.endsWith('.md')) acc.push(p);
  }
}

const files = [];
if (fs.existsSync(path.join(ROOT, 'README.md'))) files.push(path.join(ROOT, 'README.md'));
walk(path.join(ROOT, 'docs'), files);

const fenceRe = /```mermaid\r?\n([\s\S]*?)```/g;

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mmd-'));
const pptrCfg = path.join(tmp, 'puppeteer.json');
fs.writeFileSync(pptrCfg, JSON.stringify({ args: ['--no-sandbox', '--disable-setuid-sandbox'] }));

let total = 0;
const failures = [];

for (const file of files) {
  const text = fs.readFileSync(file, 'utf8');
  let m;
  let blockIndex = 0;
  while ((m = fenceRe.exec(text)) !== null) {
    total++;
    blockIndex++;
    const mmdPath = path.join(tmp, `block-${total}.mmd`);
    fs.writeFileSync(mmdPath, m[1]);
    try {
      // Run through the shell so Windows resolves mmdc.cmd (execFile can't spawn
      // a .cmd directly); on Linux/CI this is a plain `mmdc` invocation. Paths
      // are generated by this script, so the interpolation is safe.
      const svg = path.join(tmp, `block-${total}.svg`);
      execSync(`mmdc -i "${mmdPath}" -o "${svg}" -q --puppeteerConfigFile "${pptrCfg}"`, { stdio: 'pipe' });
    } catch (err) {
      const detail = (err.stderr?.toString() || err.message || '').trim().split('\n').slice(-4).join(' | ');
      failures.push(`${path.relative(ROOT, file)}  block #${blockIndex}\n      ${detail}`);
    }
  }
}

if (failures.length > 0) {
  console.error(`✗ ${failures.length}/${total} mermaid block(s) failed to render:\n`);
  for (const f of failures) console.error('  ' + f + '\n');
  process.exit(1);
}

console.log(`✓ all ${total} mermaid blocks render across ${files.length} markdown files.`);
